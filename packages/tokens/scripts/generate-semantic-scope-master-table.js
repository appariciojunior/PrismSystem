import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '../../..');

const TOKENS_PATH = path.join(repoRoot, 'packages/tokens/src/tokens.json');
const DOC_PATH = path.join(
  repoRoot,
  'packages/tokens/docs/reference/semantic-tokens.md'
);

const START_MARKER = '<!-- MASTER_SCOPE_TABLE_START -->';
const END_MARKER = '<!-- MASTER_SCOPE_TABLE_END -->';

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function isTokenLeaf(node) {
  return (
    !!node && typeof node === 'object' && 'value' in node && 'type' in node
  );
}

function walkTokenPaths(node, prefix = '', out = []) {
  if (!node || typeof node !== 'object') {
    return out;
  }

  if (isTokenLeaf(node)) {
    out.push({ path: prefix, node });
    return out;
  }

  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) {
      continue;
    }
    const next = prefix ? `${prefix}.${key}` : key;
    walkTokenPaths(value, next, out);
  }
  return out;
}

function normalizeScopes(scopes) {
  if (!Array.isArray(scopes)) {
    return [];
  }
  return [...new Set(scopes.map(String))].sort((a, b) => a.localeCompare(b));
}

function layerForTokenSet(tokenSetName) {
  if (tokenSetName === 'light/ core') {
    return 'semantic';
  }
  if (tokenSetName.startsWith('viewport/ ')) {
    return 'viewport';
  }
  if (tokenSetName === 'borderRadius') {
    return 'borderRadius';
  }
  return 'other';
}

function shouldIncludeTokenSet(tokenSetName) {
  return (
    tokenSetName === 'light/ core' ||
    tokenSetName.startsWith('viewport/ ') ||
    tokenSetName === 'borderRadius'
  );
}

function collectScopedRows(tokens) {
  const rows = [];

  for (const [tokenSet, tokenTree] of Object.entries(tokens)) {
    if (!shouldIncludeTokenSet(tokenSet)) {
      continue;
    }

    const leaves = walkTokenPaths(tokenTree);
    for (const leaf of leaves) {
      const scopes = normalizeScopes(
        leaf.node?.$extensions?.['com.figma.scopes']
      );
      if (scopes.length === 0) {
        continue;
      }

      const fullTokenPath =
        tokenSet === 'light/ core' ? leaf.path : `${tokenSet}.${leaf.path}`;

      rows.push({
        tokenPath: fullTokenPath,
        layer: layerForTokenSet(tokenSet),
        sourceSet: tokenSet,
        scopes
      });
    }
  }

  rows.sort((a, b) => a.tokenPath.localeCompare(b.tokenPath));
  return rows;
}

function toMarkdownTable(rows) {
  const header = [
    '| Token Path | Layer | Scope(s) | Source Set |',
    '| ---------- | ----- | -------- | ---------- |'
  ];

  const body = rows.map((row) => {
    const scopes = `\`${row.scopes.join('`, `')}\``;
    return `| \`${row.tokenPath}\` | ${row.layer} | ${scopes} | \`${row.sourceSet}\` |`;
  });

  return [...header, ...body].join('\n');
}

function buildGeneratedSection(rows) {
  const semanticCount = rows.filter((r) => r.layer === 'semantic').length;
  const viewportCount = rows.filter((r) => r.layer === 'viewport').length;
  const borderRadiusCount = rows.filter(
    (r) => r.layer === 'borderRadius'
  ).length;
  const total = rows.length;

  return [
    START_MARKER,
    `<!-- Generated by packages/tokens/scripts/generate-semantic-scope-master-table.js -->`,
    '',
    `Updated from \`packages/tokens/src/tokens.json\``,
    '',
    `Coverage: ${total} scoped tokens (${semanticCount} semantic + ${viewportCount} viewport + ${borderRadiusCount} borderRadius).`,
    '',
    toMarkdownTable(rows),
    END_MARKER
  ].join('\n');
}

function replaceBetweenMarkers(source, replacement) {
  const start = source.indexOf(START_MARKER);
  const end = source.indexOf(END_MARKER);

  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      `Could not find markers ${START_MARKER} and ${END_MARKER} in semantic-tokens.md`
    );
  }

  const before = source.slice(0, start);
  const after = source.slice(end + END_MARKER.length);
  return `${before}${replacement}${after}`;
}

function main() {
  const tokens = readJson(TOKENS_PATH);
  const rows = collectScopedRows(tokens);

  const doc = fs.readFileSync(DOC_PATH, 'utf8');
  const generated = buildGeneratedSection(rows);
  const nextDoc = replaceBetweenMarkers(doc, generated);

  fs.writeFileSync(DOC_PATH, nextDoc);

  console.log(
    `Updated semantic scope master table with ${rows.length} rows from tokens.json.`
  );
}

main();
